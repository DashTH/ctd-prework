# This code will take account of adult tournament entrants for a esports
# competition.

# Checks for valid months as an interger input.
month = int(input("Please enter the month you were born: (1-12): "))
if month < 0 or month > 12:
  print("Invalid Month")
  month = 0

# Checks for valid days of the month then validates months that have different
# end days.
day = int(input("Please enter the day you were born: (1-31)"))
if day < 0 or day > 31:
  print("Invalid day")
  day = 0
elif day == 31 and (month == 2 or month == 4 or month == 6 or
                    month == 9 or month == 11):
  print("Invalid day")
  day = 0
elif day > 28 and month == 2:
  print("Invalid day")
  day = 0

# Checks for a valid birth year for to determine if they are 18+.
year = int(input("Please enter the year you were born: "))
if year < 1900 or year > 2007:
  print("Invalid year")
  year = 0

# Takes the user's desired player tag which can include anything.
player_tag = input('Please enter your Player Tag: ')
if day == 0 or month == 0 or year == 0:
  print(player_tag + " does not meet the requirements to compete.")
else:
    print("Player: "+ player_tag + " " +
      "has been registered for the event!")

